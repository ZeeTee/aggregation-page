/**
 * 🔄 重启 DSH —— 轮询参数
 * ============================================================================
 * 单独成模块,是为了让单测能在**不加载 main.ts** 的前提下读到这些常量
 * (main.ts 顶层就要取 DOM,直接 import 会炸)。
 *
 * ⚠️ 这几个值不是随手定的,背后有一次真实故障:
 *
 *   `/api/dsh/login-url` 是需要密钥的接口,走**独立限流**。重启流程要轮询它来等新
 *   令牌,而 dsh 进程从启动到把 token 打印进日志,**实测需要约 8.6 秒**。
 *   原先的配置是间隔 1.2 秒、额度 5 次/分钟:于是"读旧地址 + 触发重启 + 3 次轮询"
 *   在 5.5 秒就把额度耗光了,而 token 要到 8.6 秒才出现 —— 出现的那一刻轮询已经
 *   被 429 封死,用户看到的必然是「35 秒内没取到新地址」。
 *
 * 所以:间隔要**足够长**,让额度撑过整个启动期;超时要**大于启动时间**。
 * 改动前请先看 tests/dsh-restart-ui.test.ts 里那三个断言。
 */

/** 轮询间隔。不要调小 —— 见上面的说明。 */
export const POLL_INTERVAL_MS = 2_000;

/** 总等待上限:dsh 启动约 9 秒,45 秒留足余量(也够跨过一次限流窗口)。 */
export const POLL_TIMEOUT_MS = 45_000;

/** 撞上限流时的退避时长(正常情况下不该触发,纯属兜底)。 */
export const RATE_LIMIT_BACKOFF_MS = 10_000;

/** dsh 进程启动到打印 token 的实测耗时,供单测换算额度占用。 */
export const DSH_STARTUP_MS = 9_000;

/** 一次重启流程里的固定请求数:GET 读旧地址 + POST 触发重启。 */
export const SETUP_REQUESTS = 2;

/**
 * 服务端 AUTH_RATE_LIMIT,必须与 .env 保持一致。
 * 取 30:最坏情况(轮询跑满超时)需要 2 + ceil(45/2) = 25 次,留 5 次裕量;
 * 同时仍比普通接口的 60/分钟严格一半。
 */
export const AUTH_RATE_LIMIT = 30;
